export const EPISODE_BY_ID = new Map(HOMER_EPISODES.map((episode) => [episode.id, episode]));

export function episodesForEpic(epic: EpicId): HomerEpisode[] {
  return HOMER_EPISODES.filter((episode) => episode.epic === epic);
}

export function episodesForBook(epic: EpicId, book: number): HomerEpisode[] {
  return HOMER_EPISODES.filter((episode) => episode.epic === epic && episode.book === book);
}

export function nearestEpisode(epic: EpicId, book: number): HomerEpisode {
  const episodes = episodesForEpic(epic);
  return episodes.reduce((best, episode) =>
    Math.abs(episode.book - book) < Math.abs(best.book - book) ? episode : best,
  );
}
